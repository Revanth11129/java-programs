public class eight {
 public static void main(String[] args) {
 
    
for (int row = 5; row >= 1; row--) {
    for (int space = 1; space >= row-5; space--) {
       System.out.print(" ");

    }






for (int stars = 1; stars <= row; stars++) {
    System.out.print("*");   
}

 System.out.println();   
}












 }   

}